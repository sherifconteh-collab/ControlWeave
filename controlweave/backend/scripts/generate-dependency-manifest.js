#!/usr/bin/env node
'use strict';

/**
 * Writes dependency-manifest.json: the frontend's npm dependencies (direct
 * ranges and every resolved package from its lockfile) and the container base
 * images of both Dockerfiles. The backend container ships without the
 * frontend, so the in-app dependency tracker (services/dependencyTracker.js)
 * reads the frontend side from this file; the backend side comes from the
 * backend's own package-lock.json at runtime.
 *
 *   node scripts/generate-dependency-manifest.js          write the manifest
 *   node scripts/generate-dependency-manifest.js --check  exit 1 if stale (CI)
 */

const fs = require('fs');
const path = require('path');

const { lockPackages, directDependencies, baseImages } = require('../src/utils/dependencyInventory');

const ROOT = path.join(__dirname, '..');
const FRONTEND = path.join(ROOT, '..', 'frontend');
const OUT = path.join(ROOT, 'dependency-manifest.json');

function build() {
  const pkg = JSON.parse(fs.readFileSync(path.join(FRONTEND, 'package.json'), 'utf8'));
  const lock = JSON.parse(fs.readFileSync(path.join(FRONTEND, 'package-lock.json'), 'utf8'));
  return {
    note: 'Generated by scripts/generate-dependency-manifest.js. Do not edit.',
    frontend: {
      version: pkg.version,
      direct: directDependencies(pkg, lock),
      packages: lockPackages(lock)
    },
    containers: {
      backend: baseImages(path.join(ROOT, 'Dockerfile')),
      frontend: baseImages(path.join(FRONTEND, 'Dockerfile'))
    }
  };
}

const manifest = `${JSON.stringify(build(), null, 1)}\n`;
if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== manifest) {
    process.stderr.write('dependency-manifest.json is stale: run npm run deps:manifest in controlweave/backend and commit it.\n');
    process.exit(1);
  }
  process.stdout.write('dependency-manifest.json is up to date\n');
} else {
  fs.writeFileSync(OUT, manifest);
  process.stdout.write(`Wrote ${path.relative(process.cwd(), OUT)}\n`);
}

